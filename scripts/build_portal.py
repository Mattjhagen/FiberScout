"""Deterministic offline bundle from the pinned tmobile-pass source. No network at build."""
from pathlib import Path
import gzip
import re

ROOT = Path(__file__).resolve().parents[1]

def assets():
    source = ROOT / 'tmobile-pass'
    html = (source / 'index.html').read_text()
    html = html.replace('https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/css/all.min.css', '/icons.css')
    help_text = (ROOT / 'portal-vendor/browser-help.html').read_text()
    # Keep the pinned site's actions intact; guidance works without JavaScript.
    html = html.replace('    <div class="container">', '    <div class="container">\n' + help_text, 1)
    result = {'/': ('text/html; charset=utf-8', html.encode())}
    # A dedicated Safari action page avoids changing Android's original SMS URLs.
    safari = html.replace('sms:4023587059?body=', 'sms:4023587059&amp;body=')
    safari = safari.replace(' download="Matthew_Hagen_TMobile_Fiber.vcf"', '')
    result['/safari.html'] = ('text/html; charset=utf-8', safari.encode())
    for name, mime in [('style.css','text/css'), ('avatar.JPG','image/jpeg'), ('favicon.png','image/png'), ('manifest.json','application/manifest+json'), ('Matthew_Hagen_TMobile_Fiber.vcf','text/vcard; charset=utf-8')]:
        result['/' + name] = (mime, (source / name).read_bytes())
    # Retain original icon definitions and only the solid face used by this site.
    css = (ROOT / 'portal-vendor/fontawesome/css/all.min.css').read_text()
    css = re.sub(r'@font-face\{[^}]*\}', '', css)
    css += '@font-face{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:block;src:url(/fa-solid-900.woff2) format("woff2")}'
    result['/icons.css'] = ('text/css', css.encode())
    result['/fa-solid-900.woff2'] = ('font/woff2', (ROOT / 'portal-vendor/fontawesome/webfonts/fa-solid-900.woff2').read_bytes())
    return result

def build():
    lines = ['// Generated by scripts/build_portal.py; do not edit.', '#pragma once', '#ifdef ARDUINO', '#include <Arduino.h>', '#else', '#include <cstddef>', '#include <cstdint>', '#define PROGMEM', '#endif', 'struct PortalAsset { const char *path; const char *mime; const uint8_t *data; size_t size; };']
    entries = []
    for i, (path, (mime, raw)) in enumerate(assets().items()):
        data = gzip.compress(raw, mtime=0)
        lines.append('static const uint8_t portal_%d[] PROGMEM = {%s};' % (i, ','.join(map(str,data))))
        entries.append('{"%s","%s",portal_%d,sizeof(portal_%d)}' % (path,mime,i,i))
    lines.append('static const PortalAsset portalAssets[] = {' + ','.join(entries) + '};')
    target = ROOT / 'include/portal_assets.h'
    output = '\n'.join(lines) + '\n'
    if not target.exists() or target.read_text() != output:
        target.write_text(output)

if __name__ == '__main__':
    build()
